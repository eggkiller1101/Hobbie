-- =============================================================
-- Hobbies Time Tracker — Supabase (PostgreSQL) schema
--
-- How to run: Supabase dashboard → SQL Editor → New query →
-- paste this whole file → Run. Safe to run more than once:
-- everything uses IF NOT EXISTS, so existing data is untouched.
--
-- Same model as server/db/schema.sql (the local SQLite version):
--   entrants      (dimension) — the players
--   hobbies       (dimension) — a shared catalogue of hobbies
--   time_entries  (fact)      — one row per timed session,
--                               linking a player to a hobby
-- =============================================================


-- ---------- entrants (the players) ----------
create table if not exists public.entrants (
  id          bigint      generated by default as identity primary key,
  name        text        not null,
  created_at  timestamptz not null default now(),

  -- The same rules the API enforces, as a safety net in the database itself
  constraint entrants_name_length  check (char_length(name) between 1 and 20),
  constraint entrants_name_trimmed check (name = btrim(name))
);

-- "Alex" and "alex" are the same player. Postgres has no COLLATE NOCASE,
-- so uniqueness is enforced on the lower-cased name instead.
create unique index if not exists entrants_name_unique_ci
  on public.entrants (lower(name));


-- ---------- hobbies ----------
create table if not exists public.hobbies (
  id          bigint      generated by default as identity primary key,
  name        text        not null,
  created_at  timestamptz not null default now(),

  constraint hobbies_name_not_blank check (char_length(name) > 0),
  constraint hobbies_name_trimmed   check (name = btrim(name))
);

create unique index if not exists hobbies_name_unique_ci
  on public.hobbies (lower(name));


-- ---------- time_entries (one row per timed session) ----------
create table if not exists public.time_entries (
  id                bigint      generated by default as identity primary key,
  entrant_id        bigint      not null references public.entrants (id) on delete cascade,
  hobby_id          bigint      not null references public.hobbies  (id) on delete cascade,
  started_at        timestamptz not null,            -- when "Start" was pressed
  ended_at          timestamptz,                     -- when "Stop" was pressed (null while running)
  duration_seconds  integer     not null default 0,  -- active time only, pauses excluded
  created_at        timestamptz not null default now(),

  constraint time_entries_duration_not_negative check (duration_seconds >= 0),
  constraint time_entries_ends_after_start      check (ended_at is null or ended_at >= started_at)
);

-- Postgres does NOT index foreign keys automatically (SQLite users often assume it does).
-- The first index speeds up "total time per player per hobby" (and covers entrant_id);
-- the second keeps deleting a hobby fast, because of ON DELETE CASCADE.
create index if not exists time_entries_entrant_hobby_idx
  on public.time_entries (entrant_id, hobby_id);
create index if not exists time_entries_hobby_idx
  on public.time_entries (hobby_id);


-- ---------- Security: Row Level Security (RLS) ----------
-- Supabase publishes every table in the "public" schema through its web API.
-- Anyone holding the project's public "anon" key could read or change these
-- tables unless RLS is on. With RLS on and no policies, that route is fully
-- blocked. Our Node server will connect with a trusted server-side connection
-- (the database connection string or the service_role key), which bypasses RLS.
alter table public.entrants     enable row level security;
alter table public.hobbies      enable row level security;
alter table public.time_entries enable row level security;


